"""See the toolbox work: a few real tool calls, and what came back.

It is part of the gateway image, so it runs the same from any shell:

    docker exec tb-gateway python demo.py

It takes under a minute. Set DEMO_SVG to also save the output as an image
(docs/media/demo.svg is made this way):

    docker exec -e DEMO_SVG=/app/demo.svg tb-gateway python demo.py
    docker cp tb-gateway:/app/demo.svg docs/media/demo.svg

(/app, not /tmp: /tmp lives in RAM in the container, and docker cp cannot reach it.)
"""

import asyncio
import base64
from html import escape
import json
import os
from pathlib import Path
import time
import textwrap

from fastmcp import Client
from rich.console import Console
from rich.text import Text
from rich.theme import Theme

URL = os.environ.get("TOOLBOX_URL", "http://localhost:8000/mcp")
WIDTH = 88
console = Console(record=True, width=WIDTH, theme=Theme({
    "demo.title": "bold #fdfaf0",
    "demo.tool": "bold #e5d9b4",
    "demo.muted": "#aea98d",
    "red": "#df6a56",
    "yellow": "#f5901e",
}))


# Keep the image and terminal transcript sourced from the same live calls.
image_rows = []


def export_demo_svg(tools, browser):
    """Render the live transcript as a self-contained instrument panel."""
    fonts = Path(__file__).resolve().parent / "fixtures" / "demo-fonts"
    faces = []
    for weight in (400, 700):
        encoded = base64.b64encode(
            (fonts / f"jetbrainsmono-{weight}.woff2").read_bytes()
        ).decode("ascii")
        faces.append(
            '@font-face {font-family:"JetBrains Mono";'
            f'font-weight:{weight};font-style:normal;'
            f'src:url("data:font/woff2;base64,{encoded}") format("woff2");}}'
        )
    license_text = escape((fonts / "OFL.txt").read_text(encoding="utf-8"))
    width, margin, output_x = 960, 28, 252
    content = []

    def text(value, x, y, color="#cfc3a6", font_size=16, weight=400,
             extra=""):
        content.append(
            f'<text x="{x}" y="{y}" fill="{color}" font-size="{font_size}" '
            f'font-weight="{weight}" {extra}>{escape(str(value))}</text>'
        )

    def rule(y, color="#aca38a", opacity=".18"):
        content.append(f'<path d="M {margin} {y} H {width - margin}" '
                       f'stroke="{color}" stroke-opacity="{opacity}"/>')

    def wrapped(value, x, y, available, color="#cfc3a6", size=16):
        # Embedded mono glyphs advance by .6 em; reserve a character of slack.
        columns = max(1, int(available / (size * .6)) - 1)
        for line in textwrap.wrap(" ".join(str(value).split()), width=columns,
                                  break_on_hyphens=False):
            text(line, x, y, color, size)
            y += 22
        return y

    def label(value, x, y):
        text(value, x, y, "#aea98d", 11, extra='letter-spacing="1.6"')

    label("MCP / RECORDED RUN", margin, 29)
    text("agentic toolbox", margin, 63, "#fdfaf0", 26, 700)
    text(f"{len(tools):02} tools", width - margin, 39, "#fdfaf0", 23, 700,
         extra='text-anchor="end"')
    text(f"{len(tools) - len(browser)} native / {len(browser)} stealth browser",
         width - margin, 63, "#aea98d", 13, extra='text-anchor="end"')
    endpoint_end = wrapped(URL, margin, 91, width - 2 * margin, "#aea98d", 13)
    header_bottom = endpoint_end - 7
    rule(header_bottom, "#f5901e", ".5")
    label("TOOL / ELAPSED", margin, header_bottom + 26)
    label("REQUEST / RETURNED OUTPUT", output_x, header_bottom + 26)
    y = row_top = header_bottom + 41
    for index, item in enumerate(image_rows, 1):
        rule(y)
        start = y
        text(f"{index:02}", margin, y + 28, "#aea98d", 12)
        text(item["tool"], margin + 30, y + 28, "#e5d9b4", 16, 700)
        text(f'{item["seconds"]:.1f} s', margin + 30, y + 51, "#aea98d", 13)
        y = wrapped(item["what"], output_x, y + 28,
                    width - margin - output_x, "#dbcab5", 14)
        if item.get("hits"):
            # Separate title and source columns wrap independently.
            for hit in item["hits"]:
                title_end = wrapped(hit["title"], output_x, y + 3, 442)
                site_end = wrapped(hit["site"], output_x + 460, y + 3,
                                   width - margin - output_x - 460,
                                   "#aea98d", 13)
                y = max(title_end, site_end) + 4
        else:
            for value, style in item["details"]:
                color = {"red": "#df6a56", "yellow": "#f5901e",
                         "demo.muted": "#aea98d"}.get(style, "#cfc3a6")
                y = wrapped(value, output_x, y + 3,
                            width - margin - output_x, color)
        y = max(y + 16, start + 83)
    content.append(f'<path d="M {output_x - 18} {row_top} V {y}" '
                   'stroke="#aca38a" stroke-opacity=".10"/>')
    rule(y, "#f5901e", ".5")
    label(f"{len(image_rows):02} TOOL CALLS / LIVE RESPONSE DATA", margin, y + 25)
    text("generated by gateway/demo.py", width - margin, y + 25,
         "#aea98d", 11, extra='text-anchor="end"')
    height = y + 42
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}"
        height="{height}" viewBox="0 0 {width} {height}" role="img"
        aria-labelledby="demo-title">
    <title id="demo-title">Agentic Toolbox: recorded tool output</title>
    <metadata>{license_text}</metadata>
    <style>
    {"".join(faces)}
    text {{font-family:"JetBrains Mono",monospace; font-variant-ligatures:none;}}
    </style>
    <rect width="100%" height="100%" rx="2" fill="#0e0f11"/>
    <path d="M 0 0 H {width} V {header_bottom} H 0 Z" fill="#0b0d0e"/>
    <path d="M 0 {row_top} H {output_x - 18} V {y} H 0 Z" fill="#121315"/>
    <path d="M 0 {y} H {width} V {height} H 0 Z" fill="#0b0d0e"/>
    {"".join(content)}
    <rect x=".5" y=".5" width="{width - 1}" height="{height - 1}" rx="2"
        fill="none" stroke="#aca38a" stroke-opacity=".18"/>
</svg>
'''


def data(result):
    """A tool's structured answer, or its text parsed as JSON when that is all there is."""
    sc = getattr(result, "structured_content", None)
    if isinstance(sc, dict):
        return sc.get("result", sc)
    text = "".join(getattr(c, "text", "") for c in result.content or [])
    try:
        return json.loads(text)
    except ValueError:
        return text


def row(tool, what, seconds):
    image_rows.append({"tool": tool, "what": what, "seconds": seconds, "details": []})
    took = f"{seconds:5.1f} s"
    pad = max(1, WIDTH - 16 - len(what) - len(took))
    console.print(Text.assemble((f"{tool:<15} ", "demo.tool"), what, " " * pad, (took, "demo.muted")))


def clip(text, width):
    """Shorten text to width at a word boundary, ending with an ellipsis."""
    text = " ".join(str(text).split())
    if len(text) <= width:
        return text
    cut = text[: width - 1].rsplit(" ", 1)[0].rstrip(" \\|-:,")
    return cut + "\u2026"


def detail(text, style=""):
    image_rows[-1]["details"].append((text, style))
    console.print(Text(" " * 16 + text[: WIDTH - 16], style=style))


async def call(client, tool, args):
    start = time.monotonic()
    result = await client.call_tool(tool, args, raise_on_error=False)
    return result, time.monotonic() - start


def headings(markdown):
    return [line.lstrip("#").strip() for line in markdown.splitlines() if line.startswith("## ")]


async def main():
    image_rows.clear()
    async with Client(URL, timeout=180) as c:
        tools = [t.name for t in await c.list_tools()]
        browser = [t for t in tools if t.startswith("cf_")]
        console.print(Text.assemble(("Agentic Toolbox", "demo.title"), f"  {URL}"))
        console.print(f"{len(tools)} tools: {len(tools) - len(browser)} of its own, "
                      f"{len(browser)} cf_* tools for the stealth browser\n")

        r, s = await call(c, "search_web", {"query": "model context protocol", "max_results": 3})
        row("search_web", '"model context protocol"', s)
        if r.is_error:
            detail(str(data(r)), "red")
        for i, hit in enumerate([] if r.is_error else data(r), 1):
            site = hit["url"].split("/")[2].removeprefix("www.")
            image_rows[-1].setdefault("hits", []).append({
                "title": hit["title"], "site": site,
            })
            detail(f"{i}. {clip(hit['title'], 43):<43}  {site}")

        page = "https://en.wikipedia.org/wiki/Large_language_model"
        r, s = await call(c, "fetch_page", {"url": page})
        row("fetch_page", page.removeprefix("https://"), s)
        md = data(r) if isinstance(data(r), str) and not r.is_error else ""
        sections = headings(md)
        detail(f"{len(md):,} characters of markdown, {len(sections)} sections:")
        detail(", ".join(sections[:4]) + ", ...", "demo.muted")

        r, s = await call(c, "cf_browse", {"url": "https://www.python.org/", "timeout": 60000})
        row("cf_browse", "www.python.org, in the stealth browser", s)
        d = data(r)
        title = d.get("title") if isinstance(d, dict) else None
        detail(f'page title "{title}"' if title else str(d)[:70], "" if title else "red")

        video = "https://www.youtube.com/watch?v=jNQXAC9IVRw"
        r, s = await call(c, "extract_video", {"url": video, "want_transcript": False})
        row("extract_video", video.removeprefix("https://www."), s)
        d = data(r)
        if isinstance(d, dict):
            detail(f'"{d.get("title")}", uploaded by {d.get("uploader")}, {d.get("duration_seconds")} s long')
        else:
            detail(str(d)[:70], "red")

        r, s = await call(c, "toolbox_status", {})
        row("toolbox_status", "what the watcher saw", s)
        checks = data(r).get("tools", {}) if isinstance(data(r), dict) else {}
        up = [n for n, t in checks.items() if t.get("status") == "up"]
        detail(f"{len(up)} of {len(checks)} scheduled checks passing")
        for name, t in checks.items():
            if t.get("status") != "up":
                detail(f"{name}: {t.get('status')}", "yellow")

    svg = os.environ.get("DEMO_SVG")
    if svg:
        Path(svg).write_text(export_demo_svg(tools, browser), encoding="utf-8")


if __name__ == "__main__":
    asyncio.run(main())
